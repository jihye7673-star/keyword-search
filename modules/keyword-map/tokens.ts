/** 끝 글자가 조사와 같지만 그 자체로 한 낱말인 말 */
const WHOLE_WORDS = new Set(["올가을", "초가을", "늦가을", "한가을"]);

/** 동사·형용사 활용형으로 끝나는 말은 명사형 키워드가 아니다 */
const VERB_ENDING = /(했다|한다|된다|됐다|하며|하고|하는|하면|해야|인다|있다|없다|밝혔다|말했다|전했다|지만|으며|이며|이고|라며|라고|하다|되다|[았었였렸겼졌났왔갔]다)$/;

export function tokenize(title: string): string[] {
  const text = title.replace(/\[[^\]]*\]|\([^)]*\)/g, " ");
  const tokens: string[] = [];
  for (const raw of text.split(/[^0-9A-Za-z가-힣]+/)) {
    if (!raw) continue;
    const token = stripSuffix(raw);
    if (token.length < 2) continue;
    if (/^[0-9]+[가-힣]?$/.test(token)) continue; // 숫자, 1위, 2심 같은 순위·회차 표현
    if (STOPWORDS.has(token) || VERB_ENDING.test(token)) continue;
    tokens.push(token);
  }
  return tokens;
}

function stripSuffix(word: string) {
  if (!/[가-힣]/.test(word) || WHOLE_WORDS.has(word)) return word;
  for (const suffix of SUFFIXES) {
    if (word.endsWith(suffix) && word.length - suffix.length >= 2) {
      return word.slice(0, -suffix.length);
    }
  }
  return word;
}
